    private static void EmitDescriptors(SourceWriter writer, FlowModel flow)
    {
        writer.Line("/// <summary>Capability descriptors, built once at type initialisation.</summary>");
        writer.Line("private static class Descriptors");
        writer.OpenBrace();

        foreach (var step in flow.AllSteps.Where(s => s.Kind == StepKindModel.Capability))
        {
            writer.Line(
                "public static readonly CapabilityDescriptor Step" + step.Index + " = " +
                DescriptorCall(step.CapabilityId!, step.CapabilityVersion!, step.IsIdempotent, step.SideEffects) + ";");

            if (step.IsCompensable)
            {
                // The compensation's own declarations, not two literals. They used to be
                // `true` and nothing, which made the descriptor a claim this layer invented:
                // `PolicyChain.ForCompensation` refuses a compensation retry over a
                // capability that is not idempotent, and against every plan the compiler
                // produced it was checking the literal rather than the author's
                // `[Capability(...)]`. The effects are the compensation's for the same
                // reason — `ExecutionPlan.SideEffects` unions them in, and an undo that
                // touches the ledger touches the ledger.
                var compensation = step.Compensation!;

                writer.Line(
                    "public static readonly CapabilityDescriptor Step" + step.Index + "Compensation = " +
                    DescriptorCall(
                        compensation.CapabilityId!,
                        compensation.CapabilityVersion!,
                        compensation.IsIdempotent,
                        compensation.SideEffects) + ";");
            }
        }

        writer.CloseBrace();
    }

    private static string DescriptorCall(string id, string version, bool idempotent, string[] sideEffects)
    {
        var effects = sideEffects.Length == 0
            ? string.Empty
            : ", " + string.Join(", ", sideEffects.Select(Quote));

        return "CapabilityDescriptor.Create(" + Quote(id) + ", " + Quote(version) + ", " +
               (idempotent ? "true" : "false") + effects + ")";
    }

    private static void EmitPlan(SourceWriter writer, FlowModel flow)
    {
        writer.Line("/// <summary>The compiled execution plan. Built once, shared by every invocation.</summary>");
        writer.Line("public static ExecutionPlan Plan { get; } = ExecutionPlan.Create(");
        writer.Line("    FlowDescriptor.Create(");
        writer.Line("        " + Quote(flow.FlowId) + ",");
        writer.Line("        " + Quote(flow.Version) + ",");
        writer.Line("        ExecutionProfile." + flow.Profile + ",");
        writer.Line("        " + DeadlineExpression(flow.Deadline) + "),");
        writer.Line("    StepGraph.Create(new StepNode[]");
        writer.Line("    {");

        EmitStepNodes(writer, flow.Steps);

        writer.Line("    }));");
    }

    /// <summary>
    /// Writes the step array, flattening conditionals into branch-and-jump form.
    /// </summary>
    /// <remarks>
    /// <para>
    /// The layout is <c>branch · then… · jump · otherwise…</c>. The branch carries only
    /// its false target, because the <c>then</c> block starts at the very next index; the
    /// jump exists solely so a taken <c>then</c> block skips the alternative, and is
    /// omitted when there is no alternative to skip. Nested conditionals recurse, and
    /// their indices were already assigned in this same order during analysis — which is
    /// why the array comes out contiguous and <c>StepGraph.Create</c> accepts it.
    /// </para>
    /// <para>
    /// A switch is the same shape with more blocks:
    /// <c>switch · case₀… · jump · case₁… · jump · … · default…</c>. Each block is closed
    /// by a jump to the join, except the last non-empty one, which falls into the join
    /// anyway.
    /// </para>
    /// </remarks>
    private static void EmitStepNodes(SourceWriter writer, System.Collections.Generic.IReadOnlyList<StepModel> steps)
    {
        foreach (var step in steps)
        {
            switch (step.Kind)
            {
                case StepKindModel.Condition:
                    writer.Line("        StepNode.ForBranch(" + step.Index + ", " + step.FalseTarget + "),");
                    EmitStepNodes(writer, step.Then);

                    if (step.JumpIndex is int jump)
                    {
                        writer.Line("        StepNode.ForJump(" + jump + ", " + step.JoinIndex + "),");
                        EmitStepNodes(writer, step.Otherwise);
                    }

                    break;

                case StepKindModel.Switch:
                    writer.Line("        " + SwitchNodeExpression(step) + ",");

                    foreach (var arm in step.Cases)
                    {
                        EmitStepNodes(writer, arm.Steps);

                        if (arm.JumpIndex is int caseJump)
                        {
                            writer.Line("        StepNode.ForJump(" + caseJump + ", " + step.JoinIndex + "),");
                        }
                    }

                    EmitStepNodes(writer, step.Default);
                    break;

                case StepKindModel.Parallel:
                    writer.Line("        " + ParallelNodeExpression(step) + ",");

                    foreach (var branch in step.Branches)
                    {
                        EmitStepNodes(writer, branch.Steps);
                    }

                    break;

                case StepKindModel.ForEach:
                    // `foreach · body…`, and that is the whole layout: one block, starting
                    // at the very next index, with nothing after it to skip. The body
                    // appears once however many elements the collection turns out to hold.
                    writer.Line("        " + ForEachNodeExpression(step) + ",");
                    EmitStepNodes(writer, step.Body);
                    break;

                case StepKindModel.SubFlow:
                    // One node and nothing else. The child's steps are in the child's own
                    // generated plan, so there is no block here to recurse into — which is
                    // why a flow that composes a hundred-step child emits one line.
                    writer.Line("        " + SubFlowNodeExpression(step) + ",");
                    break;

                case StepKindModel.AwaitSignal:
                    // `await · escalation…`, and no jump closes the block: the escalation is
                    // the only one of the two paths that can be contiguous, because the other
                    // is the rest of the flow. The signal path is the target on the node, one
                    // past the block, and the block falls through to the same index — so the
                    // two rejoin without a node spent saying so.
                    writer.Line("        " + StepNodeExpression(step) + ",");
                    EmitStepNodes(writer, step.Then);
                    break;

                default:
                    writer.Line("        " + StepNodeExpression(step) + ",");
                    break;
            }
        }
    }

    /// <summary>The one thing this generator says when a wait reaches it with no duration.</summary>
    /// <remarks>
    /// One sentence for both kinds because it is one invariant, and it is written once so the
    /// two arms cannot come to say different things about the same rule.
    /// </remarks>
    private static string NoDuration(string what) =>
        what + " reached the emitter with no duration on it, and the only value this " +
        "generator may write there is the duration the author declared.";

    private static string SwitchNodeExpression(StepModel step)
    {
        var targets = string.Join(
            ", ",
            step.Cases.Select(c => c.Target.ToString(CultureInfo.InvariantCulture)));

        return "StepNode.ForSwitch(" + step.Index + ", new[] { " + targets + " }, defaultTarget: " +
               step.DefaultTarget + ")";
    }

    /// <summary>
    /// Emits the fork node, with the author's <c>merge:</c> expression copied verbatim.
    /// </summary>
    /// <remarks>
    /// Verbatim rather than reconstructed from <c>MergeKindName</c>, so that
    /// <c>MergeStrategy.Quorum(RequiredChecks)</c> compiles into the plan as written and a
    /// strategy chosen through a constant on the flow keeps working. Reconstructing it
    /// would mean the generated plan disagreed with the source for every expression the
    /// name-reader could not recognise.
    /// </remarks>
    private static string ParallelNodeExpression(StepModel step)
    {
        var targets = string.Join(
            ", ",
            step.Branches
                .Where(b => b.Steps.Count > 0)
                .Select(b => b.Target.ToString(CultureInfo.InvariantCulture)));

        return "StepNode.ForParallel(" + step.Index + ", new[] { " + targets + " }, joinTarget: " +
               step.JoinIndex + ", merge: " + step.MergeExpression + ")";
    }

    /// <summary>
    /// Emits the loop node, with the author's <c>options:</c> expression copied verbatim.
    /// </summary>
    /// <remarks>
    /// Verbatim rather than reconstructed from the values, for the reason
    /// <see cref="ParallelNodeExpression"/> copies the merge: an author may write
    /// <c>new ForEachOptions { MaxDegreeOfParallelism = Concurrency }</c>, and a generator
    /// that rebuilt the object literal would disagree with the source for every expression
    /// it could not fold. The runtime clamps the bound; the generator does not evaluate it.
    /// </remarks>
    private static string ForEachNodeExpression(StepModel step) =>
        "StepNode.ForEach(" + step.Index + ", joinTarget: " + step.JoinIndex +
        ", options: " + step.OptionsExpression + ")";

    /// <summary>Emits the composition node: which flow, and how it relates to this one.</summary>
    /// <remarks>
    /// The child's <em>id</em> reaches the plan, not its plan object. A node holding another
    /// plan would make two flows' type initialisers depend on each other, which is a cycle
    /// the CLR resolves by handing one of them a null — and it would put the child's whole
    /// graph inside the parent's static state for no gain, since the thing the engine
    /// actually needs at run time comes from the dispatcher.
    /// </remarks>
    private static string SubFlowNodeExpression(StepModel step) =>
        "StepNode.ForSubFlow(" + step.Index + ", " + Quote(step.SubFlowId!) +
        ", SubFlowMode." + step.SubFlowMode + ")";

    private static string StepNodeExpression(StepModel step)
    {
        switch (step.Kind)
        {
            case StepKindModel.Emit:
                return "StepNode.ForEmit(" + step.Index + ", " + Quote(step.EventType!) + ")";

            case StepKindModel.AwaitSignal:
                // This arm used to write the author's signal and a hard-coded one-hour
                // timeout, whatever duration they declared — so a flow written to wait seven
                // days published a plan saying one hour. The model had no field to carry the
                // author's, which is why the generator refused the whole flow rather than let
                // the constant through.
                //
                // The refusal is still here, and it is still the same invariant: this
                // generator does not invent a duration. What changed is that it no longer
                // has to, because `StepModel.SignalTimeout` carries the one that was
                // written. `AwaitSignal<TSignal>(TimeSpan timeout)` has no overload without
                // a timeout, so an empty model means a half-typed buffer — and refusing it
                // keeps the choice in front of the next person "carry the author's duration"
                // rather than "put a constant back".
                //
                // The target is written only when the author declared an escalation. Writing
                // one equal to the next index instead would be a node claiming a block that
                // is not there — and the engine reads its absence as "there is nowhere for
                // this timeout to go", which is a different ending from "go to the step after
                // the wait".
                return step.SignalTimeout is { Length: > 0 } timeout
                    ? "StepNode.ForAwaitSignal(" + step.Index + ", " + Quote(step.SignalType!) +
                      ", " + timeout +
                      (step.Then.Count == 0 ? string.Empty : ", signalTarget: " + step.JoinIndex) + ")"
                    : throw new System.InvalidOperationException(
                        NoDuration("A suspension point"));

            case StepKindModel.Delay:
                // The same invariant, stated for the construct that is nothing but a
                // duration. `Delay(TimeSpan duration)` has no overload without one, so this
                // throw is unreachable from source a developer can write — and it is here
                // rather than absent so that a change which loses the expression on the way
                // to the emitter fails loudly instead of producing a wait nobody asked for.
                return step.DelayDuration is { Length: > 0 } duration
                    ? "StepNode.ForDelay(" + step.Index + ", " + duration + ")"
                    : throw new System.InvalidOperationException(NoDuration("A timer"));

            case StepKindModel.Fail:
                // No payload. The error is in `Failures` above, which is where a business
                // value belongs — the plan says only that the flow ends here.
                return "StepNode.ForFail(" + step.Index + ")";

            default:
                var compensation = step.IsCompensable
                    ? ", Descriptors.Step" + step.Index + "Compensation"
                    : string.Empty;

                return "StepNode.ForCapability(" + step.Index + ", Descriptors.Step" + step.Index +
                       compensation + PolicyArguments(step) + ")";
        }
    }

    /// <summary>
    /// The declared policy set, split into the chain that wraps the step and the chain that
    /// wraps its compensation.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <strong>Until this existed, <c>.WithPolicy(...)</c> reached the manifest and stopped.</strong>
    /// Every node was emitted as <c>ForCapability(index, capability, compensation)</c>, so
    /// <c>ExecutionPlan.HasCompensationPolicies</c> was false for every compiled flow and
    /// <c>PolicySet.CompensationRetry</c> — the one policy this runtime executes — was
    /// unreachable from the DSL. The document said the undo would be retried; the plan the
    /// engine walked said it would be dispatched once.
    /// </para>
    /// <para>
    /// <strong>The set is copied verbatim, for the reason <see cref="ParallelNodeExpression"/>
    /// copies the merge.</strong> <c>PolicySet</c>'s composition is fixed at compile time and
    /// its parameter <em>values</em> are not, so a set whose attempt count comes from
    /// configuration has to compile into the plan as the author wrote it. Rebuilding it from
    /// the kinds this layer read would freeze those values at build time and disagree with the
    /// source for every expression the reader could not fold.
    /// </para>
    /// <para>
    /// <strong>Nothing is emitted for a set the compiler could not read.</strong>
    /// <c>StepModel.PolicyKinds</c> is empty exactly when <c>PolicySetReader</c> failed to
    /// resolve the argument to a declared field or property initialiser — the same signal that
    /// keeps FLOWX1014 from firing on a guess. An expression that could not be resolved is one
    /// this emitter cannot promise will even bind inside a static initialiser in a file the
    /// author did not write, and turning a working build into a compile error there is worse
    /// than carrying nothing.
    /// </para>
    /// <para>
    /// <strong>The split is by what a policy wraps, not by which stage it runs in.</strong>
    /// <c>Audit</c> is a <c>Consistency</c> policy and stays on the step; only
    /// <c>CompensationRetry</c> moves, because only it is checked against the compensating
    /// capability's idempotency rather than the step's. That is what makes a non-idempotent
    /// <c>payment.capture</c> carrying an idempotent <c>payment.refund</c> expressible at all.
    /// </para>
    /// </remarks>
    private static string PolicyArguments(StepModel step)
    {
        if (step.PolicySetName is not { Length: > 0 } set || step.PolicyKinds.Length == 0)
        {
            return string.Empty;
        }

        var node = "Descriptors.Step" + step.Index;
        var arguments = string.Empty;

        // Nothing is emitted for a half the set is empty on, so a compensation-only set costs
        // the forward node no call at all — the same reason a step with no set at all is left
        // exactly as it was.
        if (step.PolicyKinds.Any(static kind => kind != CompensationRetryKind))
        {
            arguments += ", policies: PolicyChain.ForStep(" + set + ", " + node + ")";
        }

        // A compensation chain with no compensation to wrap is refused by StepNode, and there
        // is no compensating descriptor to check the retry's idempotency against in any case.
        // Dropping it is a silent no-op that wants a diagnostic of its own; raising one is the
        // analyzer's business, not this layer's.
        if (step.IsCompensable && step.PolicyKinds.Contains(CompensationRetryKind))
        {
            arguments += ", compensationPolicies: PolicyChain.ForCompensation(" +
                         set + ", " + node + "Compensation)";
        }

        return arguments;
    }

    /// <summary>
    /// The one policy kind that wraps a step's compensation rather than the step.
    /// </summary>
    /// <remarks>
    /// A literal rather than a reference to <c>CompensationPolicy.CompensationRetryKind</c>,
    /// because this assembly targets netstandard2.0 and cannot link against
    /// <c>FlowX.Core</c> — the same constraint that makes <c>ManifestWriter</c> keep its own
    /// copy of the stage table. Public for the same reason
    /// <c>ManifestWriter.KnownPolicyStages</c> is: so a fitness test can compare it with the
    /// real constant, because an unpinned copy of a safety-relevant name drifts silently.
    /// </remarks>
    public const string CompensationRetryKind = "CompensationRetry";

    private static string DeadlineExpression(string? iso8601)
    {
        // A flow without an explicit deadline gets thirty seconds. Stated here rather
        // than defaulted silently in the runtime: an unbounded flow is not a default
        // anyone would choose deliberately.
        return iso8601 == null
            ? "TimeSpan.FromSeconds(30)"
            : "System.Xml.XmlConvert.ToTimeSpan(" + Quote(iso8601) + ")";
    }

    private static void EmitDispatcher(
        SourceWriter writer,
        FlowModel flow,
        IReadOnlyList<StagedEvent> staged,
        IReadOnlyList<JournaledContract> journaled)
    {
        writer.Line("/// <summary>Invokes the capability behind each step index.</summary>");
        writer.Line("/// <remarks>");
        writer.Line("/// A switch, not a lookup. The engine's loop cannot know each step's types;");
        writer.Line("/// this class does, which is why nothing here is boxed and no reflection runs.");
        writer.Line("/// </remarks>");
        writer.Line("public sealed class Dispatcher : IStepDispatcher");
        writer.OpenBrace();

        EmitDispatcherFields(writer, flow);
        writer.Line();
        EmitDispatcherConstructor(writer, flow);
        writer.Line();
        EmitDispatcherExecute(writer, flow);
        writer.Line();
        EmitDispatcherCompensate(writer, flow);
        writer.Line();
        EmitDispatcherEvaluate(writer, flow);
        writer.Line();
        EmitDispatcherSelect(writer, flow);
        writer.Line();
        EmitDispatcherIteration(writer, flow);
        writer.Line();
        EmitDispatcherSubFlow(writer, flow);

        if (staged.Count > 0 || journaled.Count > 0)
        {
            writer.Line();
            EmitDispatcherDescribe(writer, staged, journaled);
        }

        if (journaled.Count > 0)
        {
            writer.Line();
            EmitDispatcherRestore(writer, journaled);
            writer.Line();
            EmitDispatcherDescribeInput(writer, journaled);
        }

        writer.CloseBrace();
    }

    /// <summary>
    /// Emits <c>BeginSubFlow</c> and <c>EnterSubFlow</c>: which flow to compose, and the
    /// input to seed into it.
    /// </summary>
    /// <remarks>
    /// <para>
    /// The pair is the whole of what the engine cannot do for itself, and it is deliberately
    /// the <em>only</em> thing generated here. Renting the child's context, deriving its
    /// deadline from this flow's, running its graph and unwinding its compensation are the
    /// engine's job and are identical for every flow; emitting them per composing flow would
    /// have put four subtle behaviours into generated source, where a mistake is hardest to
    /// see and impossible to fix without a rebuild.
    /// </para>
    /// <para>
    /// <c>EnterSubFlow</c> writes into the <em>child's</em> context, which is a different
    /// object from the one every other method here receives. That is what makes a detached
    /// child safe: the two contexts never meet, so a child outliving its parent cannot read
    /// a context that has since been reset and rented to another tenant's flow.
    /// </para>
    /// </remarks>
    private static void EmitDispatcherSubFlow(SourceWriter writer, FlowModel flow)
    {
        var subFlows = SubFlows(flow);

        writer.Line("/// <inheritdoc />");
        writer.Line("public SubFlowSource BeginSubFlow(int stepIndex, FlowContext ctx)");
        writer.OpenBrace();

        if (subFlows.Count == 0)
        {
            EmitNoSubFlow(writer, "compose");
            writer.CloseBrace();
            writer.Line();
            EmitDispatcherEnterSubFlow(writer, subFlows);
            return;
        }

        writer.Line("switch (stepIndex)");
        writer.OpenBrace();

        foreach (var step in subFlows)
        {
            writer.Line("case " + step.Index + ":");
            writer.OpenBrace();
            writer.Line(
                "return new SubFlowSource(" + step.SubFlowTypeName + ".Plan, " +
                SubFlowFieldName(step.SubFlowTypeName!) + ", SubFlowInputs.Step" + step.Index +
                "(Typed(ctx)));");
            writer.CloseBrace();
        }

        EmitSubFlowDefaultCase(writer);

        writer.CloseBrace();
        writer.CloseBrace();
        writer.Line();

        EmitDispatcherEnterSubFlow(writer, subFlows);
    }

    private static void EmitDispatcherEnterSubFlow(
        SourceWriter writer, System.Collections.Generic.List<StepModel> subFlows)
    {
        writer.Line("/// <inheritdoc />");
        writer.Line("public void EnterSubFlow(int stepIndex, in SubFlowSource source, FlowContext child)");
        writer.OpenBrace();

        if (subFlows.Count == 0)
        {
            EmitNoSubFlow(writer, "seed");
            writer.CloseBrace();
            return;
        }

        writer.Line("switch (stepIndex)");
        writer.OpenBrace();

        foreach (var step in subFlows)
        {
            writer.Line("case " + step.Index + ":");
            writer.OpenBrace();
            writer.Line("// The child's own context, never this flow's. Seeding it here is");
            writer.Line("// what lets the child's first step bind to its input by type.");
            writer.Line("child.Set((" + step.SubFlowInputTypeName + ")source.Input!);");
            writer.Line("return;");
            writer.CloseBrace();
        }

        EmitSubFlowDefaultCase(writer);

        writer.CloseBrace();
        writer.CloseBrace();
    }

    private static void EmitNoSubFlow(SourceWriter writer, string verb)
    {
        writer.Line("throw new ArgumentOutOfRangeException(");
        writer.Line("    nameof(stepIndex),");
        writer.Line("    stepIndex,");
        writer.Line("    \"This flow composes no sub-flow, so the engine never asks it to " + verb + " \" +");
        writer.Line("    \"one. Reaching this means the plan and this dispatcher came from \" +");
        writer.Line("    \"different builds.\");");
    }

    private static void EmitSubFlowDefaultCase(SourceWriter writer)
    {
        writer.Line("default:");
        writer.OpenBrace();
        writer.Line("throw new ArgumentOutOfRangeException(");
        writer.Line("    nameof(stepIndex),");
        writer.Line("    stepIndex,");
        writer.Line("    \"Step index does not name a sub-flow in the compiled plan. The plan \" +");
        writer.Line("    \"and this dispatcher are generated together, so this means they came \" +");
        writer.Line("    \"from different builds.\");");
        writer.CloseBrace();
    }

    /// <summary>
    /// Emits <c>BeginIteration</c> and <c>EnterIteration</c>: the collection each loop
    /// walks, and the element each pass over its body is for.
    /// </summary>
    /// <remarks>
    /// <para>
    /// The pair is the whole of what the engine cannot do for itself. It has no idea what a
    /// <c>ValidatedOrder.Lines</c> is, so it asks for a count and an opaque handle, then
    /// hands the handle back once per element and gets a context in return. Everything typed
    /// happens here, in generated code, which is the same division that keeps capabilities
    /// reflection-free.
    /// </para>
    /// <para>
    /// <c>EnterIteration</c> is one indexed read and one small object. It is deliberately
    /// not a <c>foreach</c> over the collection: the concurrent path runs several elements
    /// at once and would have to share a single enumerator, which no
    /// <c>IEnumerator&lt;T&gt;</c> supports.
    /// </para>
    /// </remarks>
    private static void EmitDispatcherIteration(SourceWriter writer, FlowModel flow)
    {
        var iterations = Iterations(flow);

        writer.Line("/// <inheritdoc />");
        writer.Line("public IterationSource BeginIteration(int stepIndex, FlowContext ctx)");
        writer.OpenBrace();

        if (iterations.Count == 0)
        {
            writer.Line("throw new ArgumentOutOfRangeException(");
            writer.Line("    nameof(stepIndex),");
            writer.Line("    stepIndex,");
            writer.Line("    \"This flow declares no iteration, so the engine never asks it for a \" +");
            writer.Line("    \"collection. Reaching this means the plan and this dispatcher came from \" +");
            writer.Line("    \"different builds.\");");
            writer.CloseBrace();
            writer.Line();
            EmitDispatcherEnterIteration(writer, iterations);
            return;
        }

        writer.Line("switch (stepIndex)");
        writer.OpenBrace();

        foreach (var step in iterations)
        {
            writer.Line("case " + step.Index + ":");
            writer.OpenBrace();
            writer.Line("var items = Iterations.Step" + step.Index + "(Typed(ctx));");
            writer.Line("return new IterationSource(items, items.Count);");
            writer.CloseBrace();
        }

        EmitIterationDefaultCase(writer);

        writer.CloseBrace();
        writer.CloseBrace();
        writer.Line();

        EmitDispatcherEnterIteration(writer, iterations);
    }

    private static void EmitDispatcherEnterIteration(
        SourceWriter writer, System.Collections.Generic.List<StepModel> iterations)
    {
        writer.Line("/// <inheritdoc />");
        writer.Line(
            "public FlowContext EnterIteration(int stepIndex, in IterationSource source, " +
            "int iteration, FlowContext ctx)");
        writer.OpenBrace();

        if (iterations.Count == 0)
        {
            writer.Line("throw new ArgumentOutOfRangeException(");
            writer.Line("    nameof(stepIndex),");
            writer.Line("    stepIndex,");
            writer.Line("    \"This flow declares no iteration, so the engine never asks it for an \" +");
            writer.Line("    \"element. Reaching this means the plan and this dispatcher came from \" +");
            writer.Line("    \"different builds.\");");
            writer.CloseBrace();
            return;
        }

        writer.Line("switch (stepIndex)");
        writer.OpenBrace();

        foreach (var step in iterations)
        {
            writer.Line("case " + step.Index + ":");
            writer.OpenBrace();
            writer.Line(
                "var items = (System.Collections.Generic.IReadOnlyList<" + step.ItemTypeName +
                ">)source.Items!;");
            writer.Line();
            writer.Line("// The element shadows the flow's state bag on its own type, for");
            writer.Line("// exactly this pass over the body. Writes still go to the bag.");
            writer.Line("return IterationScope.For(ctx, items[iteration]);");
            writer.CloseBrace();
        }

        EmitIterationDefaultCase(writer);

        writer.CloseBrace();
        writer.CloseBrace();
    }

    private static void EmitIterationDefaultCase(SourceWriter writer)
    {
        writer.Line("default:");
        writer.OpenBrace();
        writer.Line("throw new ArgumentOutOfRangeException(");
        writer.Line("    nameof(stepIndex),");
        writer.Line("    stepIndex,");
        writer.Line("    \"Step index does not name an iteration in the compiled plan. The plan \" +");
        writer.Line("    \"and this dispatcher are generated together, so this means they came \" +");
        writer.Line("    \"from different builds.\");");
        writer.CloseBrace();
    }

    private static void EmitDispatcherFields(SourceWriter writer, FlowModel flow)
    {
        foreach (var capability in flow.ReferencedCapabilities)
        {
            writer.Line("private readonly " + capability + " " + FieldName(capability) + ";");
        }

        foreach (var composed in flow.ComposedFlows)
        {
            writer.Line(
                "private readonly " + composed + ".Dispatcher " + SubFlowFieldName(composed) + ";");
        }
    }

    /// <summary>
    /// Emits the dispatcher's constructor: one parameter per capability, then one per
    /// composed flow.
    /// </summary>
    /// <remarks>
    /// <strong>A child's dispatcher is injected, not constructed here.</strong> Building one
    /// would mean this flow had to know the child's capabilities, which is exactly the
    /// coupling composition exists to avoid — and it would build a fresh one per parent
    /// rather than sharing the container's. Injection also means a child in another assembly
    /// costs this flow nothing but a type reference.
    /// </remarks>
    private static void EmitDispatcherConstructor(SourceWriter writer, FlowModel flow)
    {
        var parameters = string.Join(
            ", ",
            flow.ReferencedCapabilities.Select(c => c + " " + ParameterName(c))
                .Concat(flow.ComposedFlows.Select(f => f + ".Dispatcher " + SubFlowParameterName(f))));

        writer.Line("/// <summary>Capabilities and composed flows are injected, never resolved by reflection.</summary>");
        writer.Line("public Dispatcher(" + parameters + ")");
        writer.OpenBrace();

        foreach (var capability in flow.ReferencedCapabilities)
        {
            writer.Line(FieldName(capability) + " = " + ParameterName(capability) + ";");
        }

        foreach (var composed in flow.ComposedFlows)
        {
            writer.Line(SubFlowFieldName(composed) + " = " + SubFlowParameterName(composed) + ";");
        }

        writer.CloseBrace();
    }

    /// <summary>
    /// The field holding one composed flow's dispatcher.
    /// </summary>
    /// <remarks>
    /// Named from the <em>flow</em> and not from the nested <c>Dispatcher</c> type, because
    /// every child's dispatcher is called <c>Dispatcher</c> — deriving the name the way a
    /// capability's is derived would give two composed flows the same field.
    /// </remarks>
    private static string SubFlowFieldName(string flowTypeName) => "_" + SubFlowParameterName(flowTypeName);

    private static string SubFlowParameterName(string flowTypeName) =>
        ParameterName(flowTypeName) + "Dispatcher";

    private static void EmitDispatcherExecute(SourceWriter writer, FlowModel flow)
    {
        writer.Line("/// <inheritdoc />");
        writer.Line("public async ValueTask<StepOutcome> ExecuteAsync(int stepIndex, FlowContext ctx, CancellationToken ct)");
        writer.OpenBrace();
        writer.Line("switch (stepIndex)");
        writer.OpenBrace();

        // Conditions, switches, forks, loops and sub-flows have no case: the engine reaches
        // a condition through Evaluate, a switch through Select, a loop through
        // BeginIteration and a composition through BeginSubFlow, and it handles a fork, a
        // loop and a child flow entirely itself — the blocks' own steps get cases, the
        // branching node does not, and a child's steps are the child's dispatcher's
        // business. A case here would be dead code in the file the header promises is
        // readable.
        foreach (var step in flow.AllSteps
            .Where(s => s.Kind is not (StepKindModel.Condition or StepKindModel.Switch
                or StepKindModel.Parallel or StepKindModel.ForEach or StepKindModel.SubFlow))
            .OrderBy(s => s.Index))
        {
            writer.Line("case " + step.Index + ":");
            writer.OpenBrace();

            if (step.Kind == StepKindModel.Capability)
            {
                EmitCapabilityInvocation(
                    writer,
                    FieldName(step.CapabilityTypeName!),
                    InputExpression(step),
                    step.CapabilityOutput,
                    step.Location);
            }
            else if (step.Kind == StepKindModel.Fail)
            {
                // `.Fail(...)` invokes nothing; it hands the engine the error your flow
                // declared. Delivered through the same call a declined payment comes back
                // on, so the engine treats the two identically — the failure path, and the
                // unwind of everything compensable that completed before this point.
                writer.Line("return StepOutcome.Failed(Failures.Step" + step.Index + ");");
            }
            else
            {
                // Emit, AwaitSignal and Delay have no capability to call; the engine and
                // the event plugin handle them. Returning success keeps the switch total —
                // and for the two that wait, "success" is what the engine dispatches only
                // once the wait is over, so the row that follows records a wait that
                // happened rather than one that was skipped.
                writer.Line("return StepOutcome.Success;");
            }

            writer.CloseBrace();
        }

        writer.Line("default:");
        writer.OpenBrace();
        writer.Line("throw new ArgumentOutOfRangeException(");
        writer.Line("    nameof(stepIndex),");
        writer.Line("    stepIndex,");
        writer.Line("    \"Step index is outside the compiled plan. The plan and this dispatcher \" +");
        writer.Line("    \"are generated together, so this means they came from different builds.\");");
        writer.CloseBrace();

        writer.CloseBrace();
        writer.CloseBrace();
    }

    /// <summary>
    /// How one step gets its input: out of the state bag by type, or from the mapping the
    /// author wrote.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Step inputs are bound by type out of the flow's state bag. The flow's own input is
    /// seeded there by the engine; every later step reads what an earlier one returned.
    /// That is what lets a chain of differently-typed steps run through an engine that
    /// knows none of the types.
    /// </para>
    /// <para>
    /// <strong>A mapped step short-circuits that lookup entirely</strong> — it does not
    /// read the bag and does not write to it. The mapping runs on this thread, immediately
    /// before the call, and its result is an argument and nothing more. See
    /// <see cref="EmitStepInputs"/> for why the value deliberately does not live in the
    /// bag.
    /// </para>
    /// </remarks>
    private static string InputExpression(StepModel step) =>
        step.HasInputMapping
            ? "StepInputs.Step" + step.Index + "(Typed(ctx))"
            : step.CapabilityInput is null
                ? "ctx"
                : "ctx.Get<" + step.CapabilityInput + ">()";

    private static void EmitCapabilityInvocation(
        SourceWriter writer,
        string field,
        string input,
        string? outputType,
        string? location)
    {
        EmitLineDirective(writer, location);
        writer.Line("var result = await " + field + ".ExecuteAsync(" + input + ", ctx, ct).ConfigureAwait(false);");
        EmitLineDirectiveEnd(writer, location);

        writer.Line("if (!result.IsSuccess)");
        writer.OpenBrace();
        writer.Line("return StepOutcome.Failed(result.Error);");
        writer.CloseBrace();
        writer.Line();

        if (outputType is not null)
        {
            // Stored so the next step can bind to it.
            writer.Line("ctx.Set(result.Value);");
        }

        writer.Line("return StepOutcome.Success;");
    }

    private static void EmitDispatcherCompensate(SourceWriter writer, FlowModel flow)
    {
        writer.Line("/// <inheritdoc />");
        writer.Line("public async ValueTask<StepOutcome> CompensateAsync(int stepIndex, FlowContext ctx, CancellationToken ct)");
        writer.OpenBrace();
        writer.Line("switch (stepIndex)");
        writer.OpenBrace();

        foreach (var step in flow.AllSteps.Where(s => s.IsCompensable).OrderBy(s => s.Index))
        {
            writer.Line("case " + step.Index + ":");
            writer.OpenBrace();

            // The compensation binds to the step's own input — the thing it has to undo.
            // For a mapped step that means re-running the mapping rather than reading a
            // bag entry that was never written. Re-running is sound for the same reason
            // reading the bag is: the mapping is pure and deterministic (FLOWX1011), and
            // both routes see whatever the context holds at unwind time — a later step
            // that produced the same type again would move the value under an unmapped
            // compensation exactly as it moves it under this one.
            EmitCapabilityInvocation(
                writer,
                FieldName(step.CompensationTypeName!),
                InputExpression(step),
                outputType: null,
                step.Location);

            writer.CloseBrace();
        }

        writer.Line("default:");
        writer.OpenBrace();
        writer.Line("// The engine only compensates steps that declared one, so reaching");
        writer.Line("// here means the plan and this dispatcher disagree.");
        writer.Line("return StepOutcome.Success;");
        writer.CloseBrace();

        writer.CloseBrace();
        writer.CloseBrace();
    }

    private static void EmitDispatcherEvaluate(SourceWriter writer, FlowModel flow)
    {
        var conditions = flow.AllSteps
            .Where(s => s.Kind == StepKindModel.Condition)
            .OrderBy(s => s.Index)
            .ToList();

        writer.Line("/// <inheritdoc />");
        writer.Line("public bool Evaluate(int stepIndex, FlowContext ctx)");
        writer.OpenBrace();

        if (conditions.Count == 0)
        {
            // No switch at all rather than one with only a default. A flow with no
            // conditional has no branch for the engine to ask about, and an empty switch
            // reads like an oversight.
            writer.Line("throw new ArgumentOutOfRangeException(");
            writer.Line("    nameof(stepIndex),");
            writer.Line("    stepIndex,");
            writer.Line("    \"This flow declares no conditional, so the engine never asks it to \" +");
            writer.Line("    \"evaluate one. Reaching this means the plan and this dispatcher came \" +");
            writer.Line("    \"from different builds.\");");
            writer.CloseBrace();
            return;
        }

        writer.Line("switch (stepIndex)");
        writer.OpenBrace();

        foreach (var condition in conditions)
        {
            writer.Line("case " + condition.Index + ":");
            writer.OpenBrace();
            writer.Line("return Conditions.Step" + condition.Index + "(Typed(ctx));");
            writer.CloseBrace();
        }

        writer.Line("default:");
        writer.OpenBrace();
        writer.Line("throw new ArgumentOutOfRangeException(");
        writer.Line("    nameof(stepIndex),");
        writer.Line("    stepIndex,");
        writer.Line("    \"Step index does not name a branch in the compiled plan. The plan and \" +");
        writer.Line("    \"this dispatcher are generated together, so this means they came from \" +");
        writer.Line("    \"different builds.\");");
        writer.CloseBrace();

        writer.CloseBrace();
        writer.CloseBrace();
    }

    /// <summary>
    /// Emits <c>Select</c>: which case of each switch matched, by step index.
    /// </summary>
    /// <remarks>
    /// <para>
    /// The selector runs <em>once</em> and the arms are then tested against the value it
    /// produced. Compiling a switch into a chain of equality predicates would have read
    /// the selector once per arm, which is wrong for a reader and wasteful for a machine.
    /// </para>
    /// <para>
    /// The comparison is <c>EqualityComparer&lt;T&gt;.Default.Equals</c> rather than a C#
    /// <c>switch</c> statement, because a case value is an arbitrary expression and a
    /// <c>case</c> label demands a compile-time constant — <c>.Case(Channel.Retail, …)</c>
    /// would compile and <c>.Case(_defaults.Channel, …)</c> would not. The comparer is a
    /// cached static at the real type, so an <c>enum</c>, an <c>int</c> and a
    /// <c>string</c> all compare without boxing and the arm costs nothing to take.
    /// </para>
    /// </remarks>
    private static void EmitDispatcherSelect(SourceWriter writer, FlowModel flow)
    {
        var switches = Switches(flow);

        writer.Line("/// <inheritdoc />");
        writer.Line("public int Select(int stepIndex, FlowContext ctx)");
        writer.OpenBrace();

        if (switches.Count == 0)
        {
            writer.Line("throw new ArgumentOutOfRangeException(");
            writer.Line("    nameof(stepIndex),");
            writer.Line("    stepIndex,");
            writer.Line("    \"This flow declares no switch, so the engine never asks it to select a \" +");
            writer.Line("    \"case. Reaching this means the plan and this dispatcher came from \" +");
            writer.Line("    \"different builds.\");");
            writer.CloseBrace();
            return;
        }

        writer.Line("switch (stepIndex)");
        writer.OpenBrace();

        foreach (var step in switches)
        {
            writer.Line("case " + step.Index + ":");
            writer.OpenBrace();
            writer.Line("var value = Selectors.Step" + step.Index + "(Typed(ctx));");

            for (var arm = 0; arm < step.Cases.Count; arm++)
            {
                writer.Line();
                EmitLineDirective(writer, step.Cases[arm].ValueLocation);
                writer.Line(
                    "if (System.Collections.Generic.EqualityComparer<" + step.SelectorTypeName +
                    ">.Default.Equals(value, " + step.Cases[arm].Value + "))");
                writer.OpenBrace();
                writer.Line("return " + arm.ToString(CultureInfo.InvariantCulture) + ";");
                writer.CloseBrace();
                EmitLineDirectiveEnd(writer, step.Cases[arm].ValueLocation);
            }

            writer.Line();
            writer.Line("// No case matched. The engine takes the switch's default target,");
            writer.Line("// which is the `Default` block when there is one and the join when");
            writer.Line("// there is not — a value nothing matched simply continues.");
            writer.Line("return -1;");
            writer.CloseBrace();
        }

        writer.Line("default:");
        writer.OpenBrace();
        writer.Line("throw new ArgumentOutOfRangeException(");
        writer.Line("    nameof(stepIndex),");
        writer.Line("    stepIndex,");
        writer.Line("    \"Step index does not name a switch in the compiled plan. The plan and \" +");
        writer.Line("    \"this dispatcher are generated together, so this means they came from \" +");
        writer.Line("    \"different builds.\");");
        writer.CloseBrace();

        writer.CloseBrace();
        writer.CloseBrace();
    }

    private static void EmitLineDirective(SourceWriter writer, string? location)
    {
        if (location == null)
        {
            return;
        }

        var separator = location.LastIndexOf(':');

        if (separator <= 0)
        {
            return;
        }

        var file = location.Substring(0, separator);
        var line = location.Substring(separator + 1);

        // Maps the emitted call back to the .Step<T>() that declared it, so a
        // breakpoint and a stack trace both land in the developer's own file.
        writer.Line("#line " + line + " \"" + file.Replace("\\", "\\\\") + "\"");
    }

    private static void EmitLineDirectiveEnd(SourceWriter writer, string? location)
    {
        if (location != null)
        {
            writer.Line("#line default");
        }
    }

    private static string FieldName(string fullTypeName) => "_" + ParameterName(fullTypeName);

    private static string ParameterName(string fullTypeName)
    {
        var simple = fullTypeName;
        var lastDot = simple.LastIndexOf('.');

        if (lastDot >= 0)
        {
            simple = simple.Substring(lastDot + 1);
        }

        return simple.Length == 0
            ? "capability"
            : char.ToLowerInvariant(simple[0]) + simple.Substring(1);
    }

    private static string Quote(string value) =>
        "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
