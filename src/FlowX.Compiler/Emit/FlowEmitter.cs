using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using FlowX.Compiler.Model;

namespace FlowX.Compiler.Emit;

/// <summary>
/// Turns a <see cref="FlowModel"/> into the C# a flow needs at run time: its
/// compiled <c>ExecutionPlan</c> and its <c>IStepDispatcher</c>.
/// </summary>
/// <remarks>
/// <para>
/// Pure. Takes a model, returns a string, touches nothing else — which is what
/// makes every emitted shape testable by comparing text, with no compilation and
/// no Roslyn host. That is the second half of the R1 mitigation.
/// </para>
/// <para>
/// The emitted dispatcher is the reason the engine can stay type-agnostic. It holds
/// each step's typed input and output in its own fields and switches on the step
/// index, so nothing is boxed and the engine never learns what a
/// <c>ReserveRequest</c> is. See <c>IStepDispatcher</c> for why that split exists.
/// </para>
/// </remarks>
public static class FlowEmitter
{
    /// <summary>The header every generated file carries.</summary>
    public const string Header =
        "// <auto-generated>\n" +
        "//     Generated by FlowX.Compiler from the Define method of this flow.\n" +
        "//\n" +
        "//     This file is real C#, on disk, with line directives back to your source.\n" +
        "//     Set a breakpoint in it. If it is hard to read, that is a bug in the\n" +
        "//     generator, not something you are supposed to put up with.\n" +
        "// </auto-generated>\n";

    /// <summary>The file name this model's generated source should be written to.</summary>
    public static string FileNameFor(FlowModel flow)
    {
        if (flow is null)
        {
            throw new System.ArgumentNullException(nameof(flow));
        }

        return flow.FullTypeName + ".Flow.g.cs";
    }

    /// <summary>Emits the plan and dispatcher for one flow.</summary>
    /// <param name="flow">The flow to render.</param>
    /// <remarks>
    /// The overload for a compilation that declares no serialiser context, and for the tests
    /// that are about everything except the outbox. A flow whose events cannot be serialised
    /// gets a dispatcher that describes no event, which is exactly the state
    /// <c>FLOWX1024</c> reports.
    /// </remarks>
    public static string Emit(FlowModel flow) => Emit(flow, []);

    /// <summary>Emits the plan and dispatcher for one flow.</summary>
    /// <param name="flow">The flow to render.</param>
    /// <param name="jsonContexts">
    /// Every <c>JsonSerializerContext</c> the compilation declares. An <c>.Emit</c> step's
    /// event body is written through the one that declares its contract, exactly as an
    /// endpoint's request body is — see <c>EndpointEmitter</c>.
    /// </param>
    public static string Emit(FlowModel flow, IReadOnlyList<JsonContextModel> jsonContexts)
    {
        if (flow is null)
        {
            throw new System.ArgumentNullException(nameof(flow));
        }

        if (jsonContexts is null)
        {
            throw new System.ArgumentNullException(nameof(jsonContexts));
        }

        var staged = StageableEvents(flow, jsonContexts);
        var journaled = JournaledContracts(flow, jsonContexts);
        var writer = new SourceWriter();

        writer.Line(Header.TrimEnd('\n'));
        writer.Line("#nullable enable");
        writer.Line();
        writer.Line("using System;");
        writer.Line("using System.Threading;");
        writer.Line("using System.Threading.Tasks;");
        writer.Line("using FlowX;");
        writer.Line("using FlowX.Runtime;");

        // The author's usings, so a copied .Return(...) lambda resolves the same names
        // here that it resolved where it was written. Skipped when already emitted above.
        foreach (var directive in flow.Usings.Where(u => !EmittedUsings.Contains(u)))
        {
            writer.Line(directive);
        }

        writer.Line();

        var hasNamespace = !string.IsNullOrEmpty(flow.ContainingNamespace);

        if (hasNamespace)
        {
            writer.Line("namespace " + flow.ContainingNamespace);
            writer.OpenBrace();
        }

        EmitFlowPartial(writer, flow, staged, journaled);

        if (hasNamespace)
        {
            writer.CloseBrace();
        }

        return writer.ToString();
    }

    private static void EmitFlowPartial(
        SourceWriter writer,
        FlowModel flow,
        IReadOnlyList<StagedEvent> staged,
        IReadOnlyList<JournaledContract> journaled)
    {
        writer.Line("/// <summary>Compiled plan and dispatcher for <c>" + flow.FlowId + "</c>.</summary>");
        writer.Line("partial class " + flow.TypeName);
        writer.OpenBrace();

        EmitDescriptors(writer, flow);
        writer.Line();
        EmitTypedContext(writer, flow, staged);
        EmitStepInputs(writer, flow);
        EmitConditions(writer, flow);
        EmitSelectors(writer, flow);
        EmitIterations(writer, flow);
        EmitSubFlowMaps(writer, flow);
        EmitEvents(writer, flow, staged);
        EmitFailures(writer, flow);
        EmitPlan(writer, flow);
        writer.Line();
        EmitProjection(writer, flow);
        EmitSensitiveMembers(writer, flow);
        EmitStateBag(writer, journaled);
        EmitDispatcher(writer, flow, staged, journaled);

        writer.CloseBrace();
    }

    /// <summary>
    /// Emits the flow's output projection from its <c>.Return(...)</c> clause.
    /// </summary>
    /// <remarks>
    /// <para>
    /// A <c>static readonly</c> field, not a method or a lambda built per call: the engine
    /// takes it as a <c>Func</c>, and a field is allocated once at type initialisation, so
    /// passing it costs nothing and the zero-allocation budget survives contact with the
    /// feature that gives a flow an answer to return.
    /// </para>
    /// <para>
    /// <strong>Wrapped in <c>FlowContext.Untyped&lt;TIn, TOut&gt;(...)</c> rather than
    /// copied bare.</strong> The author's expression is written against
    /// <c>FlowContext&lt;TIn&gt;</c> — that is the parameter type <c>.Return(...)</c>
    /// declares, and the only one on which <c>ctx.Input</c> resolves — while
    /// <c>FlowEngine.ExecuteAsync</c> and <c>MapFlow</c> both take a
    /// <c>Func&lt;FlowContext, TOut&gt;</c>. One call adapts the first shape to the
    /// second; retyping the engine would push a generic parameter through two packages to
    /// save it. The field is still one field, still <c>static readonly</c>, and still the
    /// author's own text inside a <c>#line</c> pair.
    /// </para>
    /// </remarks>
    private static void EmitProjection(SourceWriter writer, FlowModel flow)
    {
        if (flow.ReturnProjection is null)
        {
            return;
        }

        writer.Line("/// <summary>Projects the flow's output from the finished context.</summary>");
        writer.Line("/// <remarks>");
        writer.Line("/// Your <c>.Return(...)</c> expression, copied verbatim. The engine runs it while");
        writer.Line("/// the pooled context is still rented, which is why it can read the context at all.");
        writer.Line("/// </remarks>");
        EmitLineDirective(writer, flow.ReturnLocation);
        writer.Line(
            "public static readonly Func<FlowContext, " + flow.OutputTypeName + "> Projection = " +
            "FlowContext.Untyped<" + flow.InputTypeName + ", " + flow.OutputTypeName + ">(" +
            flow.ReturnProjection + ");");
        EmitLineDirectiveEnd(writer, flow.ReturnLocation);
        writer.Line();
    }

    /// <summary>
    /// Emits the one-line conversion from the engine's context to the typed view every
    /// copied expression is written against.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <strong>This is the whole of the fix for <c>ctx.Input</c>.</strong> Every delegate on
    /// <c>IFlowBuilder</c> takes a <c>Func&lt;FlowContext&lt;TIn&gt;, …&gt;</c>, and this
    /// generator used to copy the author's lambda into a field typed at the non-generic
    /// <c>FlowContext</c> — on which <c>Input</c> is not declared. A predicate that read it
    /// compiled in the author's editor and then failed with CS1061 inside generated source.
    /// The fields below are now typed at the view, and this is what produces one.
    /// </para>
    /// <para>
    /// <c>FlowContext&lt;TIn&gt;</c> is a <c>readonly struct</c> wrapping a reference, so
    /// this allocates nothing and the JIT inlines it away. It takes the context it is
    /// handed rather than a cast, which is what makes a predicate inside a <c>ForEach</c>
    /// body work: there the context is the iteration's scope, not the flow's own.
    /// </para>
    /// </remarks>
    private static void EmitTypedContext(
        SourceWriter writer, FlowModel flow, IReadOnlyList<StagedEvent> staged)
    {
        if (!NeedsTypedContext(flow) && staged.Count == 0)
        {
            return;
        }

        writer.Line("/// <summary>The typed view your expressions receive: a struct over whatever");
        writer.Line("/// context is current, so it allocates nothing.</summary>");
        writer.Line(
            "private static FlowContext<" + flow.InputTypeName + "> Typed(FlowContext ctx) => " +
            "new FlowContext<" + flow.InputTypeName + ">(ctx);");
        writer.Line();
    }

    /// <summary>
    /// Whether the dispatcher has a call site that needs the view.
    /// </summary>
    /// <remarks>
    /// The <c>.Return(...)</c> projection deliberately does not count: it is adapted once
    /// at its own field through <c>FlowContext&lt;TIn&gt;.Untyped(...)</c>, so a linear
    /// flow — which is most flows — gets no helper it would only call from one place.
    /// </remarks>
    private static bool NeedsTypedContext(FlowModel flow) =>
        flow.AllSteps.Any(s => s.Kind is StepKindModel.Condition or StepKindModel.Switch
            or StepKindModel.ForEach or StepKindModel.SubFlow || s.HasInputMapping);

    /// <summary>The flow's explicitly mapped steps, ascending by flat index.</summary>
    private static System.Collections.Generic.List<StepModel> MappedSteps(FlowModel flow) => flow.AllSteps
        .Where(s => s.HasInputMapping)
        .OrderBy(s => s.Index)
        .ToList();

    /// <summary>An <c>.Emit</c> step this build can turn into an outbox row.</summary>
    private sealed class StagedEvent
    {
        public StagedEvent(StepModel step, string jsonContextTypeName)
        {
            Step = step;
            JsonContextTypeName = jsonContextTypeName;
        }

        /// <summary>The emit step.</summary>
        public StepModel Step { get; }

        /// <summary>The single serialiser context declaring its contract.</summary>
        public string JsonContextTypeName { get; }
    }

    /// <summary>
    /// The flow's <c>.Emit</c> steps that can actually be staged, ascending by flat index.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Three conditions, and each one is a <c>FLOWX1024</c> when it fails. <strong>The flow
    /// must be <c>Durable</c></strong> — an ephemeral execution keeps no journal, so there is
    /// no transaction for the row to be part of and staging it anywhere else would be the
    /// dual write the outbox exists to remove. <strong>The step must have a factory and a
    /// resolved contract</strong>, which is only false in a half-typed buffer.
    /// <strong>Exactly one <c>JsonSerializerContext</c> in the compilation must declare the
    /// contract</strong>: <c>JournalPayload.Of</c> takes a <c>JsonTypeInfo&lt;T&gt;</c> and has
    /// no overload that reflects over a type, which is what keeps the write path trim- and
    /// NativeAOT-safe (constraint C2, ADR-0008).
    /// </para>
    /// <para>
    /// None and several are the same answer, for the reason <c>EndpointEmitter</c> gives:
    /// picking the first of several would make the event body's shape depend on file order.
    /// </para>
    /// </remarks>
    private static List<StagedEvent> StageableEvents(
        FlowModel flow, IReadOnlyList<JsonContextModel> jsonContexts)
    {
        var staged = new List<StagedEvent>();

        if (!string.Equals(flow.Profile, "Durable", System.StringComparison.Ordinal))
        {
            return staged;
        }

        foreach (var step in flow.AllSteps
            .Where(s => s.Kind == StepKindModel.Emit)
            .OrderBy(s => s.Index))
        {
            if (step.EventFactory is null || step.EventContractTypeName is null)
            {
                continue;
            }

            var context = SingleContextFor(jsonContexts, step.EventContractTypeName);

            if (context is not null)
            {
                staged.Add(new StagedEvent(step, context));
            }
        }

        return staged;
    }

    /// <summary>A contract this flow's journal writes, and the context that writes it.</summary>
    /// <remarks>
    /// The state bag's membership, resolved once. <c>Role</c> distinguishes the flow's input —
    /// which the engine puts in the bag before the first step and which the host also records
    /// on the instance row — from a step result, which only the bag holds.
    /// </remarks>
    private sealed class JournaledContract
    {
        public JournaledContract(string typeName, string jsonContextTypeName, bool isFlowInput, int stepIndex)
        {
            TypeName = typeName;
            JsonContextTypeName = jsonContextTypeName;
            IsFlowInput = isFlowInput;
            StepIndex = stepIndex;
        }

        /// <summary>The contract, fully qualified.</summary>
        public string TypeName { get; }

        /// <summary>The single serialiser context declaring it.</summary>
        public string JsonContextTypeName { get; }

        /// <summary>Whether this is the flow's own input contract.</summary>
        public bool IsFlowInput { get; }

        /// <summary>The step that produces it, or <c>-1</c> for the flow input.</summary>
        public int StepIndex { get; }

        /// <summary>The key the composed state bag holds it under: the contract's simple name.</summary>
        public string MemberName => FlowX.Compiler.Analysis.FlowAnalyzer.SimpleName(TypeName);
    }

    /// <summary>
    /// The contracts a <c>Durable</c> flow's journal has to write, ascending by step.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <strong>What is in the state bag, and why it is exactly this.</strong> The flow's input,
    /// which the engine puts there before the first step, and the output of every capability
    /// step, which the dispatcher writes back with <c>ctx.Set</c>. A mapped step's input is
    /// not: it goes straight to the capability and is never written into the bag, which is
    /// what lets two mapped steps of one type coexist.
    /// </para>
    /// <para>
    /// <strong>Nothing at all for an <c>Ephemeral</c> flow.</strong> The engine never calls
    /// <c>DescribeStep</c> under that profile, so a writer would be unreachable code — but it
    /// would still put a candidate list, a <c>TryGet</c> chain and a member array into a type
    /// every ephemeral flow loads, and budget B2 is a hard zero on that path.
    /// </para>
    /// <para>
    /// <strong>A contract no single context declares is skipped, not guessed at.</strong>
    /// <c>FLOWX1006</c> is the error that reports it, raised by analysis and settled by
    /// <c>FlowPlanGenerator.Produce</c> against these same contexts. Emitting a call that
    /// names metadata the compilation does not have would bury that error under a cascade of
    /// "type not found" inside generated source.
    /// </para>
    /// </remarks>
    private static List<JournaledContract> JournaledContracts(
        FlowModel flow, IReadOnlyList<JsonContextModel> jsonContexts)
    {
        var journaled = new List<JournaledContract>();

        if (!string.Equals(flow.Profile, "Durable", System.StringComparison.Ordinal))
        {
            return journaled;
        }

        var seen = new System.Collections.Generic.HashSet<string>(System.StringComparer.Ordinal);

        void Add(string contract, bool isFlowInput, int stepIndex)
        {
            if (!seen.Add(contract))
            {
                return;
            }

            var context = SingleContextFor(jsonContexts, contract);

            if (context is not null)
            {
                journaled.Add(new JournaledContract(contract, context, isFlowInput, stepIndex));
            }
        }

        Add(flow.InputTypeName, isFlowInput: true, stepIndex: -1);

        foreach (var step in flow.AllSteps
            .Where(s =>
                (s.Kind == StepKindModel.Capability && !string.IsNullOrEmpty(s.CapabilityOutput)) ||
                (s.Kind == StepKindModel.AwaitSignal && !string.IsNullOrEmpty(s.SignalContractTypeName)))
            .OrderBy(s => s.Index))
        {
            // A suspension point produces a value in exactly the sense a capability step
            // does: the engine seeds the delivered signal into the bag before dispatching
            // the step, and the commit that records the step carries the snapshot. So the
            // signal's contract belongs in the state bag's membership, and the generated
            // DescribeStep and RestoreState carry it with no special case of their own.
            Add(
                step.CapabilityOutput ?? step.SignalContractTypeName!,
                isFlowInput: false,
                step.Index);
        }

        return journaled;
    }

    /// <summary>The single serialiser context declaring a contract, or <c>null</c>.</summary>
    internal static string? SingleContextFor(
        IReadOnlyList<JsonContextModel> jsonContexts, string contractTypeName)
    {
        string? found = null;

        foreach (var candidate in jsonContexts.Where(c => c.Declares(contractTypeName)))
        {
            if (found is not null)
            {
                return null;
            }

            found = candidate.TypeName;
        }

        return found;
    }

    /// <summary>
    /// Emits one <c>static readonly</c> delegate per <c>.Emit(...)</c> factory.
    /// </summary>
    /// <remarks>
    /// A field, for the reason the predicates and the selectors are: it is built once at type
    /// initialisation, so describing a step costs no delegate. The author's own expression,
    /// copied verbatim inside a <c>#line</c> pair, so a breakpoint on the event body lands on
    /// the body they wrote.
    /// <para>
    /// It runs at the step boundary, immediately before the commit, rather than when the step
    /// executed. That is the same place the journal's other payloads are built, and it is
    /// sound for the same reason a compensation may re-run a step's input mapping: the
    /// expression is pure and deterministic (FLOWX1011), and it reads the scope the step
    /// itself ran under.
    /// </para>
    /// </remarks>
    private static void EmitEvents(
        SourceWriter writer, FlowModel flow, IReadOnlyList<StagedEvent> staged)
    {
        if (staged.Count == 0)
        {
            return;
        }

        writer.Line("/// <summary>Event bodies, built once at type initialisation.</summary>");
        writer.Line("/// <remarks>");
        writer.Line("/// Each is your <c>.Emit&lt;TEvent&gt;(...)</c> expression, copied verbatim. It is");
        writer.Line("/// evaluated at the step boundary and the result is staged into the outbox by the");
        writer.Line("/// same transaction that records the step, so the state and the event commit");
        writer.Line("/// together or not at all.");
        writer.Line("/// </remarks>");
        writer.Line("private static class Events");
        writer.OpenBrace();

        foreach (var staging in staged)
        {
            EmitLineDirective(writer, staging.Step.EventFactoryLocation);
            writer.Line(
                "public static readonly Func<FlowContext<" + flow.InputTypeName + ">, " +
                staging.Step.EventContractTypeName + "> Step" + staging.Step.Index + " = " +
                staging.Step.EventFactory + ";");
            EmitLineDirectiveEnd(writer, staging.Step.EventFactoryLocation);
        }

        writer.CloseBrace();
        writer.Line();
    }

    /// <summary>
    /// Emits <c>DescribeStep</c>: the outbox row an <c>Emit</c> step contributes to its own
    /// commit.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <strong>Here rather than on the engine, for the reason nothing else typed is on the
    /// engine either.</strong> <c>JournalPayload.Of</c> needs a <c>JsonTypeInfo&lt;TEvent&gt;</c>
    /// and only generated code can name one; the step loop holds a
    /// <c>Dictionary&lt;Type, object&gt;</c> and knows no contract types at all.
    /// </para>
    /// <para>
    /// <strong>The payload carries the flow's <c>SensitiveMembers</c>.</strong> An event body
    /// is a second sink for a marked member and the worse of the two — a journal row stays in
    /// one table, where a broker fans the event out to every consumer. The control is
    /// inherited rather than re-implemented: the payload is a <c>JournalPayload</c>, which has
    /// no accessor for its value and only leaves through <c>ToJson</c>, which redacts.
    /// </para>
    /// <para>
    /// <strong>The partition key is the instance id.</strong> ADR-0018 offers ordering per
    /// <c>partition_key</c> and no global order, so this is what makes "two events from one
    /// order arrive in the order that order staged them" true. There is no DSL surface for
    /// choosing a business key yet; when there is, it replaces this expression and nothing
    /// else.
    /// </para>
    /// <para>
    /// Emitted only for a flow that has at least one stageable event. A dispatcher that
    /// describes nothing inherits <c>IStepDispatcher</c>'s default, which returns
    /// <c>StepJournalEntry.Nothing</c> — a truthful, resumable record without payloads.
    /// </para>
    /// </remarks>
    private static void EmitDispatcherDescribe(
        SourceWriter writer,
        IReadOnlyList<StagedEvent> staged,
        IReadOnlyList<JournaledContract> journaled)
    {
        var results = journaled.Where(c => !c.IsFlowInput).ToList();

        writer.Line("/// <inheritdoc />");
        writer.Line("public StepJournalEntry DescribeStep(int stepIndex, FlowContext ctx)");
        writer.OpenBrace();
        writer.Line("switch (stepIndex)");
        writer.OpenBrace();

        foreach (var staging in staged)
        {
            writer.Line("case " + staging.Step.Index + ":");
            writer.OpenBrace();
            writer.Line("return StepJournalEntry.OfEvent(new OutboxWrite");
            writer.OpenBrace();
            writer.Line("Type = " + Quote(staging.Step.EventType!) + ",");
            writer.Line("SchemaVersion = " + Quote(ManifestWriter.EventSchemaVersion) + ",");
            writer.Line();
            writer.Line("// Per-key ordering, and the key is the instance: ADR-0018 offers no");
            writer.Line("// global order, so this is the ordering a consumer actually gets.");
            writer.Line("PartitionKey = ctx.FlowInstanceId,");
            writer.Line();
            writer.Line("// The generated context writes it, and SensitiveMembers keeps a");
            writer.Line("// marked member out of the body a broker fans out.");
            writer.Line("Payload = JournalPayload.Of(");
            writer.Line("    Events.Step" + staging.Step.Index + "(Typed(ctx)),");
            writer.Line("    global::" + staging.JsonContextTypeName + ".Default,");
            writer.Line("    SensitiveMembers),");
            writer.CloseBrace(");");
            writer.CloseBrace();
        }

        foreach (var contract in results)
        {
            writer.Line("case " + contract.StepIndex + ":");
            writer.OpenBrace();
            writer.Line("// What the step produced, and the bag as it now stands. Both are");
            writer.Line("// JournalPayloads carrying SensitiveMembers, so neither can leave");
            writer.Line("// except through ToJson, which redacts (ADR-0015, commitment 5).");
            writer.Line("//");
            writer.Line("// TryGet, not Get: a step that succeeded without writing its result");
            writer.Line("// journals no result rather than failing the flow. Describing runs");
            writer.Line("// after the step and inside the commit, so a throw here would");
            writer.Line("// unwind work that had already succeeded.");
            writer.Line("return StepJournalEntry.Of(");
            writer.Line("    ctx.TryGet<" + contract.TypeName + ">(out var described)");
            writer.Line("        ? JournalPayload.Of(");
            writer.Line("            described,");
            writer.Line("            global::" + contract.JsonContextTypeName + ".Default,");
            writer.Line("            SensitiveMembers)");
            writer.Line("        : null,");
            writer.Line("    StateBag(ctx));");
            writer.CloseBrace();
        }

        writer.Line("default:");
        writer.OpenBrace();

        if (journaled.Count == 0)
        {
            writer.Line("// Every other step describes nothing: this flow journals no contract");
            writer.Line("// the compilation can serialise, and a journal of step boundaries");
            writer.Line("// without payloads is truthful and resumable.");
            writer.Line("return StepJournalEntry.Nothing;");
        }
        else
        {
            writer.Line("// A step that produced no contract of its own still moves the bag");
            writer.Line("// forward — a branch, a switch or a join — so the snapshot is what");
            writer.Line("// it has to say, and a resume reads it rather than the step count.");
            writer.Line("return StepJournalEntry.Of(null, StateBag(ctx));");
        }

        writer.CloseBrace();

        writer.CloseBrace();
        writer.CloseBrace();
    }

    /// <summary>
    /// Emits <c>RestoreState</c>: the mirror of the state-bag snapshot.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <strong>The only code that can turn the stored document back into typed values.</strong>
    /// The engine holds a <c>Dictionary&lt;Type, object&gt;</c> and no contract types, so it
    /// cannot read a bag back for the same reason it cannot write one. Reached once, before
    /// the first step of a resumed execution.
    /// </para>
    /// <para>
    /// <strong>An unknown member is ignored, deliberately.</strong> The bag's membership is the
    /// flow's shape, and a row written months ago by a build whose flow had one more step is a
    /// row this build must still be able to resume from — that is the retention window ADR-0008
    /// commits to. The <c>schemaVersion</c> stamp is the everyday case of it.
    /// </para>
    /// <para>
    /// <strong>A marked member comes back redacted, and nothing pretends otherwise.</strong>
    /// The stored value is <c>[redacted]</c>, because there is no read path that could put the
    /// original back — the journal never had it. <c>IStepDispatcher.RestoreState</c> says so on
    /// its own contract.
    /// </para>
    /// </remarks>
    private static void EmitDispatcherRestore(
        SourceWriter writer, IReadOnlyList<JournaledContract> journaled)
    {
        writer.Line("/// <inheritdoc />");
        writer.Line("public void RestoreState(FlowContext ctx, string stateBagJson)");
        writer.OpenBrace();
        writer.Line("using var document = System.Text.Json.JsonDocument.Parse(stateBagJson);");
        writer.Line();
        writer.Line("foreach (var member in document.RootElement.EnumerateObject())");
        writer.OpenBrace();
        writer.Line("switch (member.Name)");
        writer.OpenBrace();

        foreach (var contract in journaled)
        {
            writer.Line("case " + Quote(contract.MemberName) + ":");
            writer.OpenBrace();
            writer.Line(
                "ctx.Set(JournalState.Read<" + contract.TypeName + ">(" +
                "member.Value, global::" + contract.JsonContextTypeName + ".Default));");
            writer.Line("break;");
            writer.CloseBrace();
        }

        writer.Line("default:");
        writer.OpenBrace();
        writer.Line("// A member this build does not know: the schemaVersion stamp, or a");
        writer.Line("// contract a previous version of this flow wrote. Both are rows that");
        writer.Line("// must still resume, so neither is an error.");
        writer.Line("break;");
        writer.CloseBrace();

        writer.CloseBrace();
        writer.CloseBrace();
        writer.CloseBrace();
    }

    /// <summary>
    /// Emits <c>DescribeInput</c>: the trigger input as the instance row records it.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <strong>This is what closes <c>FlowHost</c>'s <c>input: null</c>.</strong> The host had
    /// no way to name a <c>JsonTypeInfo</c> for a flow's input contract, so every
    /// <c>flow_instance.input</c> ever written was NULL — a replay could not reconstruct what
    /// was requested, the audit trail had no record of it, and <c>[Sensitive]</c> on an input
    /// contract protected nothing because nothing was stored. The host now asks the
    /// dispatcher, which is the only code that can answer.
    /// </para>
    /// <para>
    /// <c>object?</c> rather than a generic, because the host reaches the dispatcher through
    /// <c>IStepDispatcher</c> and the interface cannot carry the flow's input type. The boxing
    /// is on the durable start path, which already takes a lease and a store round trip;
    /// budget B2 measures the ephemeral loop, which never reaches this.
    /// </para>
    /// <para>
    /// A value of another type is <c>Empty</c> rather than a throw. The engine refuses a
    /// mismatched input long before the journal would see it, and a start that failed on a
    /// cast inside generated code would report the wrong cause.
    /// </para>
    /// </remarks>
    private static void EmitDispatcherDescribeInput(
        SourceWriter writer, IReadOnlyList<JournaledContract> journaled)
    {
        var input = journaled.FirstOrDefault(c => c.IsFlowInput);

        writer.Line("/// <inheritdoc />");
        writer.Line("public JournalPayload DescribeInput(object? input)");
        writer.OpenBrace();

        if (input is null)
        {
            writer.Line("// No serialiser context in this compilation declares this flow's input");
            writer.Line("// contract, which FLOWX1006 reports. The instance row records nothing.");
            writer.Line("return JournalPayload.Empty;");
        }
        else
        {
            writer.Line("return input is " + input.TypeName + " typed");
            writer.Line("    ? JournalPayload.Of(typed, global::" + input.JsonContextTypeName +
                ".Default, SensitiveMembers)");
            writer.Line("    : JournalPayload.Empty;");
        }

        writer.CloseBrace();
    }

    /// <summary>
    /// Emits <c>StateBag</c>: the snapshot, composed by <c>JournalPayload</c> and not here.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <strong>The single most consequential line in this file is the one that is missing.</strong>
    /// This method hands named values to <c>JournalPayload.OfState</c> and never writes a
    /// document itself. A generated writer that reached for a <c>Utf8JsonWriter</c> would be a
    /// second exit from <c>JournalPayload</c> and would need its own copy of the redaction
    /// pass — which is precisely the arrangement <c>JournalPayload</c>'s own remarks were
    /// written to make unreachable, and which would put a <c>[Sensitive]</c> account number
    /// into a table retained for months. Composition happens inside the payload, so the bag
    /// leaves through the one <c>ToJson</c> that redacts.
    /// </para>
    /// <para>
    /// <strong>Present members only.</strong> A flow's bag holds what has actually been set:
    /// a branch not taken produced no result, and a snapshot claiming a member the flow never
    /// had would be rehydrated into a resumed run as a value no step made.
    /// </para>
    /// <para>
    /// The list is allocated per call, on the durable path only. That is the same bargain the
    /// commit itself makes — a store round trip is already happening — and the ephemeral loop
    /// never reaches this method, so budget B2's hard zero is untouched.
    /// </para>
    /// </remarks>
    private static void EmitStateBag(SourceWriter writer, IReadOnlyList<JournaledContract> journaled)
    {
        if (journaled.Count == 0)
        {
            return;
        }

        writer.Line("/// <summary>The flow's state bag as the journal records it.</summary>");
        writer.Line("/// <remarks>");
        writer.Line("/// Named values handed to <c>JournalPayload.OfState</c>, which composes the");
        writer.Line("/// document and redacts it. This method writes no JSON, so there is no second");
        writer.Line("/// exit from the payload and no second copy of the redaction rule.");
        writer.Line("/// </remarks>");
        writer.Line("private static JournalPayload StateBag(FlowContext ctx)");
        writer.OpenBrace();
        writer.Line(
            "var members = new System.Collections.Generic.List<JournalMember>(" +
            journaled.Count.ToString(System.Globalization.CultureInfo.InvariantCulture) + ");");
        writer.Line();

        foreach (var contract in journaled)
        {
            writer.Line(
                "if (ctx.TryGet<" + contract.TypeName + ">(out var " +
                LocalNameFor(contract) + "))");
            writer.OpenBrace();
            writer.Line(
                "members.Add(JournalMember.Of(" + Quote(contract.MemberName) + ", " +
                LocalNameFor(contract) + ", global::" + contract.JsonContextTypeName + ".Default));");
            writer.CloseBrace();
            writer.Line();
        }

        writer.Line("return JournalPayload.OfState(members, SensitiveMembers);");
        writer.CloseBrace();
        writer.Line();
    }

    /// <summary>A local name for a journaled contract, unique within <c>StateBag</c>.</summary>
    /// <remarks>
    /// Derived from the contract's simple name rather than from the step index, because the
    /// same contract can be produced by two steps and is one member of the bag either way.
    /// </remarks>
    private static string LocalNameFor(JournaledContract contract)
    {
        var name = contract.MemberName;

        return char.ToLowerInvariant(name[0]) + name.Substring(1) + "State";
    }

    /// <summary>
    /// Emits one <c>static readonly</c> delegate per
    /// <c>.Step&lt;TCapability, TStepIn&gt;(map)</c> input mapping.
    /// </summary>
    /// <remarks>
    /// <para>
    /// A field, for the reason the predicates, the selectors and the sub-flow mappings are:
    /// built once at type initialisation rather than once per execution, so a mapped step
    /// costs no delegate allocation on the hot path. Budget B2 is a hard zero and a lambda
    /// built at the call site would have lost it for every flow that maps a step.
    /// </para>
    /// <para>
    /// <strong>Where the mapped value lives: nowhere but the call site.</strong> The
    /// dispatcher passes the result of this delegate straight to the capability and does
    /// not write it into the state bag. The bag is keyed on <c>typeof(T)</c> and a mapping
    /// exists precisely because no earlier step put a <c>TStepIn</c> there, so writing one
    /// back would invent a producer FLOWX1020 cannot see, and two mapped steps of the same
    /// type in one flow would overwrite each other's input. As a local, each mapped step
    /// has its own delegate and its own value, and neither is visible to anything else.
    /// </para>
    /// <para>
    /// Typed at the <c>TStepIn</c> C# inferred rather than at the capability's declared
    /// input, so the field's type is the one the author's lambda actually returns. FLOWX1029
    /// has already refused the case where the two are unrelated, which is what makes passing
    /// the first where the second is declared compile.
    /// </para>
    /// </remarks>
    private static void EmitStepInputs(SourceWriter writer, FlowModel flow)
    {
        var mapped = MappedSteps(flow);

        if (mapped.Count == 0)
        {
            return;
        }

        writer.Line("/// <summary>Step input mappings, built once at type initialisation.</summary>");
        writer.Line("/// <remarks>");
        writer.Line("/// Each is your <c>.Step&lt;TCapability, TStepIn&gt;(...)</c> expression, copied");
        writer.Line("/// verbatim. They obey the same determinism rule as a condition — context, flow");
        writer.Line("/// input and prior step results only — so that a replay hands the step the input");
        writer.Line("/// it had before. The result goes straight to the capability and is never written");
        writer.Line("/// into the state bag, so two mapped steps of the same type cannot collide.");
        writer.Line("/// </remarks>");
        writer.Line("private static class StepInputs");
        writer.OpenBrace();

        foreach (var step in mapped)
        {
            EmitLineDirective(writer, step.StepInputMapLocation);
            writer.Line(
                "public static readonly Func<FlowContext<" + flow.InputTypeName + ">, " +
                step.StepInputTypeName + "> Step" + step.Index + " = " + step.StepInputMap + ";");
            EmitLineDirectiveEnd(writer, step.StepInputMapLocation);
        }

        writer.CloseBrace();
        writer.Line();
    }

    /// <summary>
    /// Emits the names of the contract members marked <c>[Sensitive]</c>.
    /// </summary>
    /// <remarks>
    /// This is what turns the attribute from a fact recorded in the manifest into
    /// something a transport can act on. The endpoint uses it to strip matching keys out
    /// of a Problem Details body, which is the only path in this release that serialises
    /// anything a capability attached to an error.
    /// <para>
    /// Emitted even when empty, unlike the manifest's array: a caller passing
    /// <c>Flow.SensitiveMembers</c> must not have to know whether the flow has any, and a
    /// missing field would be a compile error rather than an empty guard.
    /// </para>
    /// </remarks>
    private static void EmitSensitiveMembers(SourceWriter writer, FlowModel flow)
    {
        var members = flow.SensitiveInputMembers
            .Concat(flow.SensitiveOutputMembers)
            .Distinct()
            .OrderBy(m => m, System.StringComparer.Ordinal)
            .ToList();

        writer.Line("/// <summary>Contract members declared <c>[Sensitive]</c>, ordinally sorted.</summary>");
        writer.Line("/// <remarks>");
        writer.Line("/// Pass to <c>MapFlow</c> so their values are stripped from an error response.");
        writer.Line("/// </remarks>");
        writer.Line(
            "public static readonly string[] SensitiveMembers = " +
            (members.Count == 0
                ? "System.Array.Empty<string>();"
                : "new[] { " + string.Join(", ", members.Select(m => "\"" + m + "\"")) + " };"));
        writer.Line();
    }

